import { readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

export const schemaFiles = [
  '000_ekapon_schema.sql', '005_census_submissions.sql', '006_census_submitter_retention.sql',
  '008_profile_preferences_undo.sql', '007_operations.sql', '009_notification_archive.sql',
  '010_reporting_workflows.sql', '011_program_interest.sql', '012_qr_stubs.sql',
  '013_program_workspace.sql', '014_read_performance_indexes.sql', '015_data_quality_reviews.sql',
  '016_registry_workspace.sql', '017_census_registry_bridge.sql', '018_census_unknown_fields.sql',
  '019_census_review_consistency.sql', '020_navigation_badges.sql', '021_field_record_consistency.sql',
  '022_daily_read_indexes.sql', '023_workflow_redesign.sql', '024_private_file_storage.sql', '026_salin_integration.sql', '027_salin_stubs.sql', '028_superadmin_only.sql', '029_census_request_id.sql',
];
const sha = value => createHash('sha256').update(value).digest('hex');

/** Generate from reviewed migration sources, never from a local database or environment. */
export async function buildHostingSchema() {
  const sources = [];
  const chunks = [];
  for (const file of schemaFiles) {
    let source = (await readFile(new URL(`../db/${file}`, import.meta.url), 'utf8')).replace(/\r\n/g, '\n');
    sources.push({ file, sha256: sha(source) });
    if (file === '000_ekapon_schema.sql') {
      const start = source.indexOf('-- Sample staff accounts support');
      const end = source.indexOf('-- The current dashboard has', start);
      if (start < 0 || end < 0) throw new Error('Bootstrap account markers changed; review hosting schema generation.');
      source = source.slice(0, start) + '-- Hosting starts with no accounts; use 02-configure-access.sql.\n\n' + source.slice(end);
      source = source.replace("'Password reset required'\n", "'Password reset required',\n    'On hold'\n");
      if (!source.includes("'On hold'")) throw new Error('Fresh enum transformation failed.');
    }
    if (file === '007_operations.sql') {
      const partTwo = source.indexOf('-- ======================= PART 2');
      if (partTwo < 0) throw new Error('Operations migration boundary changed.');
      source = source.slice(partTwo); // On hold is already part of the fresh enum.
    }
    source = source.replace(/^BEGIN;\s*$/gm, '').replace(/^COMMIT;\s*$/gm, '');
    chunks.push(`-- SOURCE: db/${file}\n${source.trim()}`);
  }
  const sql = `-- GENERATED by npm run hosting:schema; do not edit this file manually.
-- EMPTY INSTALL ONLY. No local records, generated history, default accounts or credentials.
-- On hold is declared in the initial enum, so this fresh install is one atomic transaction.
BEGIN;
DO $$ BEGIN
  IF to_regnamespace('ekapon') IS NOT NULL THEN
    RAISE EXCEPTION 'Fresh install refused: ekapon already exists. Inspect and back up this project; use an empty project instead.';
  END IF;
  IF EXISTS(SELECT 1 FROM pg_roles WHERE rolname='ekapon_api') THEN
    RAISE EXCEPTION 'Fresh install refused: ekapon_api already exists. Review existing setup instead of overwriting it.';
  END IF;
END $$;

${chunks.join('\n\n')}

-- No database password is embedded. Enable the API login separately in the SQL Editor.
CREATE ROLE ekapon_api NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
GRANT ekapon_admin TO ekapon_api;
GRANT USAGE ON SCHEMA extensions TO ekapon_api;
REVOKE CREATE ON SCHEMA public FROM ekapon_api;
REVOKE EXECUTE ON ALL FUNCTIONS IN SCHEMA ekapon FROM PUBLIC;
ALTER DEFAULT PRIVILEGES IN SCHEMA ekapon REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;
DO $$ DECLARE api_role text; BEGIN
  FOREACH api_role IN ARRAY ARRAY['anon','authenticated'] LOOP
    IF EXISTS(SELECT 1 FROM pg_roles WHERE rolname=api_role) THEN
      EXECUTE format('REVOKE ALL ON SCHEMA ekapon FROM %I',api_role);
      EXECUTE format('REVOKE ALL ON ALL TABLES IN SCHEMA ekapon FROM %I',api_role);
      EXECUTE format('REVOKE ALL ON ALL SEQUENCES IN SCHEMA ekapon FROM %I',api_role);
      EXECUTE format('REVOKE ALL ON ALL FUNCTIONS IN SCHEMA ekapon FROM %I',api_role);
    END IF;
  END LOOP;
END $$;
CREATE TABLE ekapon.schema_migrations(file text PRIMARY KEY,sha256 text NOT NULL,applied_at timestamptz NOT NULL DEFAULT now());
REVOKE ALL ON ekapon.schema_migrations FROM PUBLIC;
GRANT SELECT ON ekapon.schema_migrations TO ekapon_admin;
INSERT INTO ekapon.schema_migrations(file,sha256) VALUES
${sources.map(s => `('${s.file}','${s.sha256}')`).join(',\n')};
COMMIT;
`;
  return { sql, manifest: { format: 'ekapon-empty-hosting-schema-v1', schemaSha256: sha(sql), sources, accounts: 0, operationalRecords: 0 } };
}
