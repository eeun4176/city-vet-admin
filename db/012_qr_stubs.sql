-- Staff QR stub inventory and attendance. Apply after 011_program_interest.sql.
-- Existing resident history and dashboard records are retained.
BEGIN;

CREATE TABLE IF NOT EXISTS ekapon.stub_batches (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reference text NOT NULL UNIQUE,
  campaign_id bigint NOT NULL REFERENCES ekapon.program_interest_campaigns(id) ON DELETE RESTRICT,
  recipient_id bigint NOT NULL REFERENCES ekapon.accounts(id) ON DELETE RESTRICT,
  recipient_name text NOT NULL,
  barangay_id integer NOT NULL REFERENCES ekapon.barangays(id) ON DELETE RESTRICT,
  requested_quantity integer NOT NULL CHECK (requested_quantity BETWEEN 1 AND 500),
  approved_quantity integer CHECK (approved_quantity BETWEEN 1 AND 500),
  status text NOT NULL DEFAULT 'Requested' CHECK (status IN ('Requested','Approved','Rejected','Printed','Handed over')),
  note text CHECK (note IS NULL OR length(note) <= 1000),
  review_note text CHECK (review_note IS NULL OR length(review_note) <= 1000),
  program_snapshot jsonb NOT NULL CHECK (jsonb_typeof(program_snapshot) = 'object'),
  requested_by bigint NOT NULL REFERENCES ekapon.accounts(id) ON DELETE RESTRICT,
  reviewed_by bigint REFERENCES ekapon.accounts(id) ON DELETE RESTRICT,
  printed_by bigint REFERENCES ekapon.accounts(id) ON DELETE RESTRICT,
  handed_over_by bigint REFERENCES ekapon.accounts(id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(), reviewed_at timestamptz,
  printed_at timestamptz, handed_over_at timestamptz,
  CHECK ((status IN ('Requested','Rejected') AND approved_quantity IS NULL)
      OR (status IN ('Approved','Printed','Handed over') AND approved_quantity IS NOT NULL)),
  CHECK (status <> 'Rejected' OR coalesce(length(btrim(review_note)),0) >= 3),
  CHECK (status NOT IN ('Printed','Handed over') OR printed_at IS NOT NULL),
  CHECK (status <> 'Handed over' OR handed_over_at IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS stub_batches_recipient_idx ON ekapon.stub_batches(recipient_id,created_at DESC,id DESC);
CREATE INDEX IF NOT EXISTS stub_batches_campaign_idx ON ekapon.stub_batches(campaign_id,status,created_at DESC);

CREATE TABLE IF NOT EXISTS ekapon.stub_tickets (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_id bigint NOT NULL REFERENCES ekapon.stub_batches(id) ON DELETE RESTRICT,
  code text NOT NULL UNIQUE CHECK (code ~ '^CVS1\.[A-Za-z0-9_-]{22}$'),
  status text NOT NULL DEFAULT 'Available' CHECK (status IN ('Available','Issued','Redeemed','Cancelled')),
  owner_snapshot jsonb CHECK (owner_snapshot IS NULL OR jsonb_typeof(owner_snapshot) = 'object'),
  pets_snapshot jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(pets_snapshot) = 'array' AND jsonb_array_length(pets_snapshot) <= 3),
  owner_barangay_id integer REFERENCES ekapon.barangays(id) ON DELETE RESTRICT,
  interest_person_id bigint REFERENCES ekapon.program_interest_people(id) ON DELETE RESTRICT,
  issued_by bigint REFERENCES ekapon.accounts(id) ON DELETE RESTRICT, issued_at timestamptz,
  redeemed_by bigint REFERENCES ekapon.accounts(id) ON DELETE RESTRICT, redeemed_at timestamptz,
  cancelled_by bigint REFERENCES ekapon.accounts(id) ON DELETE RESTRICT, cancelled_at timestamptz,
  cancel_reason text CHECK (cancel_reason IS NULL OR length(btrim(cancel_reason)) BETWEEN 3 AND 1000),
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (status NOT IN ('Issued','Redeemed') OR (owner_snapshot IS NOT NULL AND owner_barangay_id IS NOT NULL AND jsonb_array_length(pets_snapshot) BETWEEN 1 AND 3 AND issued_at IS NOT NULL)),
  CHECK ((status = 'Redeemed') = (redeemed_at IS NOT NULL)),
  CHECK ((status = 'Cancelled') = (cancelled_at IS NOT NULL)),
  CHECK (status <> 'Cancelled' OR cancel_reason IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS stub_tickets_batch_idx ON ekapon.stub_tickets(batch_id,status,id);
CREATE INDEX IF NOT EXISTS stub_tickets_owner_scope_idx ON ekapon.stub_tickets(owner_barangay_id,status,batch_id);

CREATE TABLE IF NOT EXISTS ekapon.program_attendance (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id uuid NOT NULL UNIQUE,
  payload_hash text NOT NULL CHECK (payload_hash ~ '^[a-f0-9]{64}$'),
  campaign_id bigint NOT NULL REFERENCES ekapon.program_interest_campaigns(id) ON DELETE RESTRICT,
  source text NOT NULL CHECK (source IN ('Stub','Walk-in')),
  stub_id bigint UNIQUE REFERENCES ekapon.stub_tickets(id) ON DELETE RESTRICT,
  owner_snapshot jsonb NOT NULL CHECK (jsonb_typeof(owner_snapshot) = 'object'),
  owner_identity text NOT NULL,
  owner_barangay_id integer NOT NULL REFERENCES ekapon.barangays(id) ON DELETE RESTRICT,
  pets_snapshot jsonb NOT NULL CHECK (jsonb_typeof(pets_snapshot) = 'array' AND jsonb_array_length(pets_snapshot) BETWEEN 1 AND 10),
  program_snapshot jsonb NOT NULL CHECK (jsonb_typeof(program_snapshot) = 'object'),
  attended_on date NOT NULL,
  duplicate_confirmed boolean NOT NULL DEFAULT false,
  duplicate_reason text CHECK (duplicate_reason IS NULL OR length(btrim(duplicate_reason)) BETWEEN 3 AND 1000),
  late_entry_reason text CHECK (late_entry_reason IS NULL OR length(btrim(late_entry_reason)) BETWEEN 3 AND 1000),
  encoded_by bigint NOT NULL REFERENCES ekapon.accounts(id) ON DELETE RESTRICT,
  encoded_by_name text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  status text NOT NULL DEFAULT 'Submitted' CHECK (status IN ('Submitted','Voided')),
  voided_by bigint REFERENCES ekapon.accounts(id) ON DELETE RESTRICT, voided_at timestamptz,
  void_reason text CHECK (void_reason IS NULL OR length(btrim(void_reason)) BETWEEN 3 AND 1000),
  CHECK ((source = 'Stub') = (stub_id IS NOT NULL)),
  CHECK (source <> 'Stub' OR jsonb_array_length(pets_snapshot) <= 3),
  CHECK (NOT duplicate_confirmed OR duplicate_reason IS NOT NULL),
  CHECK ((status = 'Voided') = (voided_at IS NOT NULL)),
  CHECK (status <> 'Voided' OR (voided_by IS NOT NULL AND void_reason IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS program_attendance_campaign_idx ON ekapon.program_attendance(campaign_id,status,created_at DESC,id DESC);
CREATE INDEX IF NOT EXISTS program_attendance_scope_idx ON ekapon.program_attendance(campaign_id,owner_barangay_id,status);
CREATE INDEX IF NOT EXISTS program_attendance_duplicate_idx ON ekapon.program_attendance(campaign_id,owner_identity) WHERE status = 'Submitted';
CREATE INDEX IF NOT EXISTS program_attendance_mobile_duplicate_idx ON ekapon.program_attendance(campaign_id,owner_barangay_id,(owner_snapshot->>'mobile')) WHERE status = 'Submitted';

-- Audit deliberately stores references and actor/action only; never QR bytes or owner/pet snapshots.
CREATE TABLE IF NOT EXISTS ekapon.stub_activity (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campaign_id bigint NOT NULL REFERENCES ekapon.program_interest_campaigns(id) ON DELETE RESTRICT,
  batch_id bigint REFERENCES ekapon.stub_batches(id) ON DELETE RESTRICT,
  stub_id bigint REFERENCES ekapon.stub_tickets(id) ON DELETE RESTRICT,
  attendance_id bigint REFERENCES ekapon.program_attendance(id) ON DELETE RESTRICT,
  actor_id bigint NOT NULL REFERENCES ekapon.accounts(id) ON DELETE RESTRICT,
  action text NOT NULL CHECK (action IN ('batch-requested','batch-approved','batch-rejected','batch-printed','batch-reprinted','batch-handed-over','stub-issued','manual-issue-recorded','stub-cancelled','stub-redeemed','walk-in-submitted','attendance-voided')),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS stub_activity_campaign_idx ON ekapon.stub_activity(campaign_id,created_at DESC,id DESC);
CREATE INDEX IF NOT EXISTS dashboard_workflow_attendance_idx ON ekapon.dashboard_records((record_data->>'attendanceId')) WHERE record_data->>'workflow' = 'qr-stubs-v1';

-- The canonical attendance table retains the protected snapshots. Its compact
-- activity log is sufficient; avoid copying those snapshots into general audit.
DROP TRIGGER IF EXISTS dashboard_records_audit ON ekapon.dashboard_records;
DROP TRIGGER IF EXISTS dashboard_records_audit_insert ON ekapon.dashboard_records;
DROP TRIGGER IF EXISTS dashboard_records_audit_update ON ekapon.dashboard_records;
DROP TRIGGER IF EXISTS dashboard_records_audit_delete ON ekapon.dashboard_records;
CREATE TRIGGER dashboard_records_audit_insert AFTER INSERT ON ekapon.dashboard_records
  FOR EACH ROW WHEN (coalesce(NEW.record_data->>'workflow','') <> 'qr-stubs-v1') EXECUTE FUNCTION ekapon.audit_row();
CREATE TRIGGER dashboard_records_audit_update AFTER UPDATE ON ekapon.dashboard_records
  FOR EACH ROW WHEN (coalesce(NEW.record_data->>'workflow','') <> 'qr-stubs-v1' AND coalesce(OLD.record_data->>'workflow','') <> 'qr-stubs-v1') EXECUTE FUNCTION ekapon.audit_row();
CREATE TRIGGER dashboard_records_audit_delete AFTER DELETE ON ekapon.dashboard_records
  FOR EACH ROW WHEN (coalesce(OLD.record_data->>'workflow','') <> 'qr-stubs-v1') EXECUTE FUNCTION ekapon.audit_row();

GRANT SELECT, INSERT, UPDATE ON ekapon.stub_batches, ekapon.stub_tickets, ekapon.program_attendance TO ekapon_admin;
GRANT SELECT, INSERT ON ekapon.stub_activity TO ekapon_admin;
GRANT USAGE, SELECT ON SEQUENCE ekapon.stub_batches_id_seq, ekapon.stub_tickets_id_seq,
  ekapon.program_attendance_id_seq, ekapon.stub_activity_id_seq TO ekapon_admin;
COMMIT;
