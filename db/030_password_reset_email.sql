-- 030: Paravets reset a forgotten password with a code sent to their email.
-- * accounts.email is the paravet's own address, saved only after they confirm a
--   code sent to it (email_verified_at), so codes never go to a mistyped address.
-- * email_codes holds the 6-digit codes (hashed, 10 minutes, 5 tries) for
--   confirming an email and for resetting a password.
-- * sessions_valid_after: a reset signs the account out everywhere else
--   (sessions issued before it stop working).
-- Additive and idempotent: safe to run twice. Apply after 029.
BEGIN;
ALTER TABLE ekapon.accounts ADD COLUMN IF NOT EXISTS email text CHECK (email IS NULL OR length(email) <= 254);
ALTER TABLE ekapon.accounts ADD COLUMN IF NOT EXISTS email_verified_at timestamptz;
ALTER TABLE ekapon.accounts ADD COLUMN IF NOT EXISTS sessions_valid_after timestamptz;
CREATE UNIQUE INDEX IF NOT EXISTS accounts_email_uq ON ekapon.accounts(lower(email)) WHERE email IS NOT NULL;
GRANT SELECT (email, email_verified_at, sessions_valid_after) ON ekapon.accounts TO ekapon_admin;
GRANT UPDATE (email, email_verified_at, sessions_valid_after) ON ekapon.accounts TO ekapon_admin;
CREATE TABLE IF NOT EXISTS ekapon.email_codes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id bigint NOT NULL REFERENCES ekapon.accounts(id) ON DELETE CASCADE,
  purpose text NOT NULL CHECK (purpose IN ('verify-email', 'reset-password')),
  email text NOT NULL CHECK (length(email) <= 254),
  code_hash text NOT NULL,
  attempts integer NOT NULL DEFAULT 0,
  expires_at timestamptz NOT NULL,
  used_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS email_codes_account_idx ON ekapon.email_codes(account_id, purpose, created_at DESC);
GRANT SELECT, INSERT, UPDATE ON ekapon.email_codes TO ekapon_admin;
GRANT USAGE, SELECT ON SEQUENCE ekapon.email_codes_id_seq TO ekapon_admin;
COMMIT;
