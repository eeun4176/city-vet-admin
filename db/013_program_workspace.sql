-- Program timing is separate from schedule JSON and from closing paper encoding.
BEGIN;
CREATE TABLE IF NOT EXISTS ekapon.program_runtime (
  program_record_id bigint PRIMARY KEY REFERENCES ekapon.dashboard_records(id) ON DELETE RESTRICT,
  actual_started_at timestamptz,
  actual_finished_at timestamptz,
  version integer NOT NULL DEFAULT 1 CHECK (version > 0),
  updated_by bigint NOT NULL REFERENCES ekapon.accounts(id) ON DELETE RESTRICT,
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (actual_finished_at IS NULL OR (actual_started_at IS NOT NULL AND actual_finished_at >= actual_started_at))
);
CREATE TABLE IF NOT EXISTS ekapon.program_workspace_activity (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  program_record_id bigint NOT NULL REFERENCES ekapon.dashboard_records(id) ON DELETE RESTRICT,
  actor_id bigint NOT NULL REFERENCES ekapon.accounts(id) ON DELETE RESTRICT,
  action text NOT NULL CHECK (action IN ('created','updated','connected','started','finished','timing-corrected')),
  reason text CHECK (reason IS NULL OR length(btrim(reason)) BETWEEN 3 AND 1000),
  before_data jsonb,
  after_data jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS program_workspace_activity_program_idx ON ekapon.program_workspace_activity(program_record_id,id DESC);
CREATE INDEX IF NOT EXISTS dashboard_program_date_idx ON ekapon.dashboard_records((coalesce(record_data->>'date',record_data->>'programDate','')),id) WHERE dataset='programs' AND archived=false;
GRANT SELECT, INSERT, UPDATE ON ekapon.program_runtime TO ekapon_admin;
GRANT SELECT, INSERT ON ekapon.program_workspace_activity TO ekapon_admin;
GRANT USAGE, SELECT ON SEQUENCE ekapon.program_workspace_activity_id_seq TO ekapon_admin;
COMMIT;
