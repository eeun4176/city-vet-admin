-- Existing duplicate requests remain visible for explicit resolution. New writes
-- are serialized per barangay even when old installations contain duplicates.
CREATE OR REPLACE FUNCTION ekapon.enforce_active_demand() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.campaign_type='program_request' AND NEW.status IN ('gathering','requested','approved','scheduled') THEN
  PERFORM pg_advisory_xact_lock(73023,NEW.host_barangay_id);
  IF EXISTS(SELECT 1 FROM ekapon.program_interest_campaigns c WHERE c.host_barangay_id=NEW.host_barangay_id AND c.campaign_type='program_request' AND c.status IN ('gathering','requested','approved','scheduled') AND c.id<>NEW.id) THEN
   RAISE EXCEPTION 'An active request already exists for this barangay' USING ERRCODE='23505';
  END IF;
 END IF;
 RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS active_demand_guard ON ekapon.program_interest_campaigns;
CREATE TRIGGER active_demand_guard BEFORE INSERT OR UPDATE OF status,host_barangay_id ON ekapon.program_interest_campaigns FOR EACH ROW EXECUTE FUNCTION ekapon.enforce_active_demand();
DO $$ BEGIN
 IF NOT EXISTS(SELECT 1 FROM ekapon.program_interest_campaigns WHERE campaign_type='program_request' AND status IN ('gathering','requested','approved','scheduled') GROUP BY host_barangay_id HAVING count(*)>1) THEN
  CREATE UNIQUE INDEX IF NOT EXISTS one_active_barangay_demand ON ekapon.program_interest_campaigns(host_barangay_id) WHERE campaign_type='program_request' AND status IN ('gathering','requested','approved','scheduled');
 END IF;
END $$;
