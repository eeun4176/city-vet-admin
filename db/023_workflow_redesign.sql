CREATE OR REPLACE FUNCTION ekapon.sync_paravet_directory() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.account_type::text='Paravet' THEN
  UPDATE ekapon.dashboard_records SET record_data=record_data||jsonb_build_object('name',NEW.full_name,'firstName',NEW.first_name,'middleName',coalesce(NEW.middle_name,''),'lastName',NEW.last_name,'suffix',coalesce(NEW.suffix,''),'mobile',coalesce(NEW.mobile,''),'barangay',coalesce((SELECT name FROM ekapon.barangays WHERE id=NEW.barangay_id),'')),archived=NEW.archived_at IS NOT NULL,updated_at=now() WHERE dataset='paravets' AND record_data->>'accountId'=NEW.id::text;
 END IF;
 RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS paravet_directory_assignment ON ekapon.accounts;
CREATE TRIGGER paravet_directory_assignment AFTER UPDATE OF first_name,middle_name,last_name,suffix,mobile,barangay_id,archived_at ON ekapon.accounts FOR EACH ROW EXECUTE FUNCTION ekapon.sync_paravet_directory();
CREATE OR REPLACE FUNCTION ekapon.workflow_notice(p_campaign bigint,p_barangay integer,p_title text,p_body text,p_link text) RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,ekapon AS $$
DECLARE actor ekapon.accounts;
BEGIN
 actor:=ekapon.actor_account(ARRAY['SuperAdmin','Admin','Paravet']);
 IF actor.account_type::text='Paravet' AND (p_barangay IS NULL OR p_barangay<>actor.barangay_id OR NOT EXISTS(SELECT 1 FROM ekapon.program_interest_campaigns c WHERE c.id=p_campaign AND (c.host_barangay_id=actor.barangay_id OR EXISTS(SELECT 1 FROM ekapon.program_interest_allowed_barangays a WHERE a.campaign_id=c.id AND a.barangay_id=actor.barangay_id)))) THEN RAISE EXCEPTION 'Notice outside assigned area' USING ERRCODE='42501'; END IF;
 INSERT INTO ekapon.notifications(recipient_id,kind,title,body,link)
 SELECT id,'program',left(p_title,160),left(p_body,1000),left(p_link,300) FROM ekapon.accounts WHERE status='Active' AND archived_at IS NULL AND ((p_barangay IS NULL AND account_type::text IN ('Admin','SuperAdmin')) OR (p_barangay IS NOT NULL AND account_type::text='Paravet' AND barangay_id=p_barangay));
END $$;
REVOKE ALL ON FUNCTION ekapon.workflow_notice(bigint,integer,text,text,text) FROM PUBLIC;
