-- Run after db/009_notification_archive.sql.
-- Adds safe undo/redo metadata for census approvals and workbook import de-duplication.
BEGIN;

CREATE TABLE IF NOT EXISTS ekapon.census_review_snapshots (
    submission_id  uuid PRIMARY KEY REFERENCES ekapon.census_submissions(id) ON DELETE CASCADE,
    actor_id       bigint NOT NULL REFERENCES ekapon.accounts(id) ON DELETE RESTRICT,
    owner_scope    uuid[] NOT NULL,
    before_owners  jsonb NOT NULL CHECK (jsonb_typeof(before_owners) = 'array'),
    before_pets    jsonb NOT NULL CHECK (jsonb_typeof(before_pets) = 'array'),
    after_owners   jsonb NOT NULL CHECK (jsonb_typeof(after_owners) = 'array'),
    after_pets     jsonb NOT NULL CHECK (jsonb_typeof(after_pets) = 'array'),
    review_note    text,
    captured_at    timestamptz NOT NULL DEFAULT now(),
    undone_at      timestamptz
);

CREATE TABLE IF NOT EXISTS ekapon.census_submission_status_history (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id  uuid NOT NULL REFERENCES ekapon.census_submissions(id) ON DELETE CASCADE,
    actor_id       bigint NOT NULL REFERENCES ekapon.accounts(id) ON DELETE RESTRICT,
    actor_name     text NOT NULL,
    from_status    text NOT NULL CHECK (from_status IN ('pending', 'approved', 'rejected', 'withdrawn')),
    to_status      text NOT NULL CHECK (to_status IN ('pending', 'approved', 'rejected', 'withdrawn')),
    action         text NOT NULL CHECK (action IN ('review', 'status-edit', 'undo', 'redo')),
    note           text,
    created_at     timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS census_submission_status_history_idx
    ON ekapon.census_submission_status_history (submission_id, created_at DESC);

CREATE TABLE IF NOT EXISTS ekapon.spay_neuter_report_imports (
    sha256          text PRIMARY KEY CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    batch_id        uuid NOT NULL UNIQUE REFERENCES ekapon.dashboard_import_batches(batch_id) ON DELETE CASCADE,
    actor_id        bigint NOT NULL REFERENCES ekapon.accounts(id) ON DELETE RESTRICT,
    filename        text NOT NULL CHECK (length(filename) BETWEEN 1 AND 180),
    row_count       integer NOT NULL CHECK (row_count > 0),
    procedure_count integer NOT NULL CHECK (procedure_count > 0),
    created_at      timestamptz NOT NULL DEFAULT now()
);

GRANT SELECT, INSERT, UPDATE, DELETE ON ekapon.census_review_snapshots TO ekapon_admin;
GRANT SELECT, INSERT ON ekapon.census_submission_status_history TO ekapon_admin;
GRANT USAGE, SELECT ON SEQUENCE ekapon.census_submission_status_history_id_seq TO ekapon_admin;
GRANT SELECT, INSERT, DELETE ON ekapon.spay_neuter_report_imports TO ekapon_admin;

COMMIT;
