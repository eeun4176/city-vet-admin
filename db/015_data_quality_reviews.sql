-- Human review metadata only. Never merges, deletes, or rewrites registry records.
BEGIN;
CREATE TABLE IF NOT EXISTS ekapon.data_quality_reviews (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  left_record_id bigint NOT NULL REFERENCES ekapon.dashboard_records(id) ON DELETE RESTRICT,
  right_record_id bigint NOT NULL REFERENCES ekapon.dashboard_records(id) ON DELETE RESTRICT,
  status text NOT NULL DEFAULT 'Needs review' CHECK (status IN ('Needs review','Distinct records','Duplicate confirmed','More information needed')),
  record_fingerprint text NOT NULL,
  version integer NOT NULL DEFAULT 1 CHECK (version > 0),
  updated_by bigint NOT NULL REFERENCES ekapon.accounts(id) ON DELETE RESTRICT,
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(left_record_id,right_record_id), CHECK (left_record_id < right_record_id)
);
CREATE TABLE IF NOT EXISTS ekapon.data_quality_activity (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  review_id bigint NOT NULL REFERENCES ekapon.data_quality_reviews(id) ON DELETE RESTRICT,
  actor_id bigint NOT NULL REFERENCES ekapon.accounts(id) ON DELETE RESTRICT,
  action text NOT NULL CHECK (action IN ('flagged','reviewed')),
  status text NOT NULL,
  reason text NOT NULL CHECK (length(btrim(reason)) BETWEEN 3 AND 1000),
  record_fingerprint text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS data_quality_activity_review_idx ON ekapon.data_quality_activity(review_id,id DESC);
GRANT SELECT, INSERT, UPDATE ON ekapon.data_quality_reviews TO ekapon_admin;
GRANT SELECT, INSERT ON ekapon.data_quality_activity TO ekapon_admin;
GRANT USAGE, SELECT ON SEQUENCE ekapon.data_quality_reviews_id_seq, ekapon.data_quality_activity_id_seq TO ekapon_admin;
COMMIT;
