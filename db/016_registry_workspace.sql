BEGIN;
CREATE TABLE IF NOT EXISTS ekapon.registry_requests (
 request_id uuid PRIMARY KEY,actor_id bigint NOT NULL REFERENCES ekapon.accounts(id) ON DELETE RESTRICT,
 payload_hash text NOT NULL,result jsonb NOT NULL,created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS ekapon.registry_activity (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 request_id uuid NOT NULL REFERENCES ekapon.registry_requests(request_id) ON DELETE RESTRICT,
 record_id bigint NOT NULL REFERENCES ekapon.dashboard_records(id) ON DELETE RESTRICT,
 actor_id bigint NOT NULL REFERENCES ekapon.accounts(id) ON DELETE RESTRICT,
 action text NOT NULL CHECK(action IN ('owner-created','pet-created','owner-updated','pet-updated','owner-link-corrected','owner-details-synced')),
 reason text, before_data jsonb,after_data jsonb NOT NULL,created_at timestamptz NOT NULL DEFAULT now(),
 CHECK(action<>'owner-link-corrected' OR length(btrim(reason))>=3)
);
CREATE INDEX IF NOT EXISTS registry_activity_record_idx ON ekapon.registry_activity(record_id,id DESC);
GRANT SELECT,INSERT ON ekapon.registry_requests,ekapon.registry_activity TO ekapon_admin;
GRANT USAGE,SELECT ON SEQUENCE ekapon.registry_activity_id_seq TO ekapon_admin;
COMMIT;
