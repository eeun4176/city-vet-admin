BEGIN;
-- Compact counters contain no owner/pet payloads. Each bucket's revision is
-- transactional: a late commit changes the fingerprint even after a visit.
CREATE TABLE IF NOT EXISTS ekapon.navigation_changes (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 node_id text NOT NULL,barangay_id integer NOT NULL DEFAULT 0,
 recipient_id bigint NOT NULL DEFAULT 0,actor_id bigint NOT NULL,
 campaign_id bigint NOT NULL DEFAULT 0,revision bigint NOT NULL DEFAULT 1,
 UNIQUE(node_id,barangay_id,recipient_id,actor_id,campaign_id)
);
CREATE INDEX IF NOT EXISTS navigation_changes_node_idx ON ekapon.navigation_changes(node_id,recipient_id,barangay_id);
CREATE TABLE IF NOT EXISTS ekapon.navigation_seen (
 account_id bigint NOT NULL REFERENCES ekapon.accounts(id) ON DELETE CASCADE,
 node_id text NOT NULL,scope_key text NOT NULL,fingerprint text NOT NULL,
 observed_at bigint NOT NULL,PRIMARY KEY(account_id,node_id,scope_key)
);
GRANT SELECT ON ekapon.navigation_changes TO ekapon_admin;
GRANT SELECT,INSERT,UPDATE ON ekapon.navigation_seen TO ekapon_admin;

CREATE OR REPLACE FUNCTION ekapon.touch_navigation(p_node text,p_barangay integer DEFAULT 0,p_recipient bigint DEFAULT 0,p_campaign bigint DEFAULT 0)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,ekapon AS $$
DECLARE actor bigint:=nullif(current_setting('app.account_id',true),'')::bigint;
BEGIN
 -- No historical backfill or invented actor: only new changes attributed to staff.
 IF actor IS NULL THEN RETURN; END IF;
 INSERT INTO ekapon.navigation_changes(node_id,barangay_id,recipient_id,actor_id,campaign_id)
 VALUES(p_node,coalesce(p_barangay,0),coalesce(p_recipient,0),actor,coalesce(p_campaign,0))
 ON CONFLICT(node_id,barangay_id,recipient_id,actor_id,campaign_id)
 DO UPDATE SET revision=navigation_changes.revision+1;
END $$;
REVOKE ALL ON FUNCTION ekapon.touch_navigation(text,integer,bigint,bigint) FROM PUBLIC;

CREATE OR REPLACE FUNCTION ekapon.navigation_change_trigger()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,ekapon AS $$
DECLARE data jsonb; prior jsonb; item jsonb; node text; area integer; campaign bigint; recipient bigint; sub uuid; scope integer; resource jsonb;
BEGIN
 IF TG_OP<>'INSERT' THEN prior:=to_jsonb(OLD); END IF;
 IF TG_OP<>'DELETE' THEN data:=to_jsonb(NEW); END IF;
 -- Skip timestamp-only touches, login bookkeeping, photos and preferences.
 IF TG_OP='UPDATE' AND (prior-ARRAY['updated_at','last_login_at','failed_attempts','failed_login_count','locked_until','profile_photo','locale','theme'])
   IS NOT DISTINCT FROM (data-ARRAY['updated_at','last_login_at','failed_attempts','failed_login_count','locked_until','profile_photo','locale','theme']) THEN RETURN NULL; END IF;
 FOR item IN SELECT DISTINCT value FROM jsonb_array_elements(jsonb_build_array(prior,data)) WHERE value<>'null'::jsonb LOOP
  area:=coalesce((item->>'barangay_id')::integer,0);campaign:=0;recipient:=0;
  IF TG_TABLE_NAME='dashboard_records' THEN
   resource:=item->'record_data';IF coalesce((resource->>'_sampleData')::boolean,false) THEN CONTINUE; END IF;
   area:=coalesce(ekapon.find_barangay(resource->>'barangay'),0);
   node:=CASE item->>'dataset' WHEN 'owners' THEN 'owners' WHEN 'pets' THEN 'pets' WHEN 'respondents' THEN 'respondents' WHEN 'participants' THEN 'participants' WHEN 'paravets' THEN 'paravets' WHEN 'services' THEN 'services' WHEN 'stubs' THEN 'stubs' WHEN 'programs' THEN 'programs' END;
   IF node='programs' THEN SELECT c.id INTO campaign FROM ekapon.program_interest_campaigns c WHERE c.program_record_id=(item->>'id')::bigint; END IF;
   IF node IS NOT NULL THEN PERFORM ekapon.touch_navigation(node,area,0,coalesce(campaign,0)); END IF;
   IF node='programs' THEN PERFORM ekapon.touch_navigation('program-day',area,0,coalesce(campaign,0)); END IF;
   IF node IN ('owners','pets') THEN PERFORM ekapon.touch_navigation('quality',area); END IF;
   IF node IN ('owners','pets','participants','respondents','services','programs') THEN PERFORM ekapon.touch_navigation('reports',area); END IF;
  ELSIF TG_TABLE_NAME IN ('census_submissions','census_owners','census_pets') THEN
   IF TG_TABLE_NAME='census_submissions' THEN resource:=item;
   ELSE
    IF TG_TABLE_NAME='census_owners' THEN sub:=(item->>'submission_id')::uuid;
    ELSE SELECT o.submission_id INTO sub FROM ekapon.census_owners o WHERE o.id=(item->>'owner_id')::uuid; END IF;
    SELECT to_jsonb(s) INTO resource FROM ekapon.census_submissions s WHERE s.id=sub;
   END IF;
   IF resource IS NOT NULL THEN
    PERFORM ekapon.touch_navigation('census-'||(resource->>'status'),coalesce((resource->>'barangay_id')::integer,0));
    PERFORM ekapon.touch_navigation('census-mine',0,(resource->>'submitted_by')::bigint);
   END IF;
  ELSIF TG_TABLE_NAME IN ('program_interest_campaigns','program_interest_allowed_barangays','program_interest_people','stub_batches','stub_tickets','program_attendance','program_runtime') THEN
   IF TG_TABLE_NAME='program_interest_campaigns' THEN campaign:=(item->>'id')::bigint;
   ELSIF TG_TABLE_NAME='program_runtime' THEN SELECT c.id INTO campaign FROM ekapon.program_interest_campaigns c WHERE c.program_record_id=(item->>'program_record_id')::bigint;
   ELSIF TG_TABLE_NAME='stub_tickets' THEN SELECT b.campaign_id,b.barangay_id,b.recipient_id INTO campaign,area,recipient FROM ekapon.stub_batches b WHERE b.id=(item->>'batch_id')::bigint;
   ELSE campaign:=(item->>'campaign_id')::bigint; END IF;
   SELECT c.host_barangay_id INTO scope FROM ekapon.program_interest_campaigns c WHERE c.id=campaign;
   IF TG_TABLE_NAME IN ('stub_batches','stub_tickets') THEN
    IF TG_TABLE_NAME='stub_batches' THEN recipient:=(item->>'recipient_id')::bigint; END IF;
    PERFORM ekapon.touch_navigation('stubs',area,recipient,campaign);
   ELSIF TG_TABLE_NAME='program_attendance' THEN PERFORM ekapon.touch_navigation('reports',(item->>'owner_barangay_id')::integer,0,campaign);
    PERFORM ekapon.touch_navigation('participants',(item->>'owner_barangay_id')::integer,0,campaign);
   ELSE
    IF TG_TABLE_NAME='program_interest_people' THEN area:=(item->>'residence_barangay_id')::integer; ELSE area:=0; END IF;
    PERFORM ekapon.touch_navigation('program-interest',area,0,campaign);
   END IF;
   PERFORM ekapon.touch_navigation('programs',coalesce(scope,0),0,campaign);
   PERFORM ekapon.touch_navigation('program-day',coalesce(scope,0),0,campaign);
  ELSIF TG_TABLE_NAME='data_quality_reviews' THEN
   SELECT coalesce(ekapon.find_barangay(d.record_data->>'barangay'),0) INTO area FROM ekapon.dashboard_records d WHERE d.id=(item->>'left_record_id')::bigint;
   PERFORM ekapon.touch_navigation('quality',area);
  ELSIF TG_TABLE_NAME='permission_requests' THEN
   PERFORM ekapon.touch_navigation('access');PERFORM ekapon.touch_navigation('access-request',0,(item->>'requester_id')::bigint);
  ELSIF TG_TABLE_NAME='access_grants' THEN PERFORM ekapon.touch_navigation('access');
  ELSIF TG_TABLE_NAME='issue_reports' THEN PERFORM ekapon.touch_navigation('issues');
  ELSIF TG_TABLE_NAME='accounts' THEN
   IF item->>'account_type' IN ('Admin','Paravet') THEN PERFORM ekapon.touch_navigation('accounts'); END IF;
  ELSIF TG_TABLE_NAME='barangays' THEN PERFORM ekapon.touch_navigation('barangays');
  ELSIF TG_TABLE_NAME='registry_owners' THEN
   PERFORM ekapon.touch_navigation('census-summary',area);PERFORM ekapon.touch_navigation('census-front',area);
  ELSIF TG_TABLE_NAME='registry_pets' THEN
   SELECT o.barangay_id INTO area FROM ekapon.registry_owners o WHERE o.id=(item->>'owner_id')::uuid;
   PERFORM ekapon.touch_navigation('census-summary',area);PERFORM ekapon.touch_navigation('census-front',area);
  END IF;
 END LOOP;
 RETURN NULL;
END $$;
DO $$ DECLARE tab text; BEGIN
 FOREACH tab IN ARRAY ARRAY['dashboard_records','census_submissions','census_owners','census_pets','program_interest_campaigns','program_interest_allowed_barangays','program_interest_people','stub_batches','stub_tickets','program_attendance','program_runtime','data_quality_reviews','permission_requests','access_grants','issue_reports','accounts','barangays','registry_owners','registry_pets'] LOOP
  EXECUTE format('DROP TRIGGER IF EXISTS navigation_changed ON ekapon.%I',tab);
  EXECUTE format('CREATE TRIGGER navigation_changed AFTER INSERT OR UPDATE OR DELETE ON ekapon.%I FOR EACH ROW EXECUTE FUNCTION ekapon.navigation_change_trigger()',tab);
 END LOOP;
END $$;
CREATE INDEX IF NOT EXISTS census_pending_badge_idx ON ekapon.census_submissions(status) WHERE status='pending';
COMMIT;
