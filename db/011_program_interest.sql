-- Retire resident ID verification and add staff-managed program interest tracking.
-- Apply after db/010_reporting_workflows.sql on existing installations.
BEGIN;

-- ID images are no longer needed for any active workflow. Keep decision and
-- submission metadata for audit while removing every stored image payload.
UPDATE ekapon.id_verifications
   SET image = NULL,
       purged_at = COALESCE(purged_at, now())
 WHERE image IS NOT NULL;

DROP TRIGGER IF EXISTS prelistings_require_verified ON ekapon.prelistings;
DROP FUNCTION IF EXISTS ekapon.require_verified_user();
REVOKE ALL ON ekapon.id_verifications, ekapon.id_verification_log FROM ekapon_admin;
-- Keep only non-image history columns available to reports and protected backups.
GRANT SELECT (id, user_id, barangay_id, status, reviewer_id, reviewer_name,
              reviewed_at, decision_reason, submitted_at, purge_after, purged_at)
    ON ekapon.id_verifications TO ekapon_admin;
GRANT SELECT (id, verification_id, user_id, user_name, reviewer_id, reviewer_name,
              outcome, reason, created_at)
    ON ekapon.id_verification_log TO ekapon_admin;
DROP FUNCTION IF EXISTS ekapon.submit_id_photo(bytea, text);
DROP FUNCTION IF EXISTS ekapon.get_id_photo(bigint);
DROP FUNCTION IF EXISTS ekapon.decide_id_verification(bigint, text, text);

CREATE TABLE IF NOT EXISTS ekapon.program_interest_campaigns (
    id                       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference                text NOT NULL UNIQUE,
    campaign_type            text NOT NULL CHECK (campaign_type IN ('program_request', 'program_day')),
    host_barangay_id         integer NOT NULL REFERENCES ekapon.barangays(id) ON DELETE RESTRICT,
    program_record_id        bigint REFERENCES ekapon.dashboard_records(id) ON DELETE RESTRICT,
    requested_target_people  integer NOT NULL DEFAULT 100 CHECK (requested_target_people BETWEEN 1 AND 100000),
    approved_target_people   integer CHECK (approved_target_people BETWEEN 1 AND 100000),
    processes                text[] NOT NULL CHECK (
        cardinality(processes) > 0
        AND processes <@ ARRAY['Microchipping', 'Anti-Rabies Vaccine', 'Neuter/Spay']::text[]
    ),
    status                   text NOT NULL CHECK (status IN ('gathering', 'requested', 'approved', 'rejected', 'scheduled', 'closed')),
    request_note             text CHECK (request_note IS NULL OR length(request_note) <= 1000),
    review_note              text CHECK (review_note IS NULL OR length(review_note) <= 1000),
    created_by               bigint NOT NULL REFERENCES ekapon.accounts(id) ON DELETE RESTRICT,
    created_at               timestamptz NOT NULL DEFAULT now(),
    submitted_at             timestamptz,
    reviewed_by              bigint REFERENCES ekapon.accounts(id) ON DELETE SET NULL,
    reviewed_at              timestamptz,
    closed_at                timestamptz,
    CHECK (campaign_type <> 'program_day' OR program_record_id IS NOT NULL),
    CHECK (program_record_id IS NULL OR status IN ('scheduled', 'closed'))
);
CREATE UNIQUE INDEX IF NOT EXISTS program_interest_program_record_uq
    ON ekapon.program_interest_campaigns(program_record_id) WHERE program_record_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS program_interest_campaign_status_idx
    ON ekapon.program_interest_campaigns(host_barangay_id, status, created_at DESC);

CREATE TABLE IF NOT EXISTS ekapon.program_interest_allowed_barangays (
    campaign_id  bigint NOT NULL REFERENCES ekapon.program_interest_campaigns(id) ON DELETE CASCADE,
    barangay_id  integer NOT NULL REFERENCES ekapon.barangays(id) ON DELETE RESTRICT,
    added_by     bigint NOT NULL REFERENCES ekapon.accounts(id) ON DELETE RESTRICT,
    added_at     timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (campaign_id, barangay_id)
);

CREATE TABLE IF NOT EXISTS ekapon.program_interest_people (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id           bigint NOT NULL REFERENCES ekapon.program_interest_campaigns(id) ON DELETE RESTRICT,
    owner_name            text NOT NULL CHECK (length(btrim(owner_name)) BETWEEN 1 AND 120),
    mobile                text CHECK (mobile IS NULL OR mobile ~ '^09[0-9]{2}[- ]?[0-9]{3}[- ]?[0-9]{4}$'),
    residence_barangay_id integer NOT NULL REFERENCES ekapon.barangays(id) ON DELETE RESTRICT,
    pets                  jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (
        jsonb_typeof(pets) = 'array' AND jsonb_array_length(pets) <= 10
    ),
    status                text NOT NULL DEFAULT 'interested' CHECK (status IN ('interested', 'withdrawn')),
    duplicate_confirmed   boolean NOT NULL DEFAULT false,
    created_by            bigint NOT NULL REFERENCES ekapon.accounts(id) ON DELETE RESTRICT,
    created_at            timestamptz NOT NULL DEFAULT now(),
    updated_at            timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS program_interest_people_campaign_idx
    ON ekapon.program_interest_people(campaign_id, status, created_at DESC);
CREATE INDEX IF NOT EXISTS program_interest_people_barangay_idx
    ON ekapon.program_interest_people(residence_barangay_id, campaign_id);

-- Keep a compact, privacy-conscious audit trail for intake actions. Owner and
-- pet details are deliberately excluded from this log.
CREATE TABLE IF NOT EXISTS ekapon.program_interest_activity (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id bigint REFERENCES ekapon.program_interest_campaigns(id) ON DELETE SET NULL,
    person_id   bigint,
    actor_id    bigint REFERENCES ekapon.accounts(id) ON DELETE SET NULL,
    actor_name  text NOT NULL,
    action      text NOT NULL CHECK (action IN ('created', 'interest-added', 'interest-updated', 'interest-withdrawn', 'request-submitted', 'request-approved', 'request-rejected', 'program-scheduled', 'program-access-updated', 'closed', 'reopened')),
    created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS program_interest_activity_campaign_idx
    ON ekapon.program_interest_activity(campaign_id, created_at DESC);

GRANT SELECT, INSERT, UPDATE ON ekapon.program_interest_campaigns,
    ekapon.program_interest_people, ekapon.program_interest_activity TO ekapon_admin;
GRANT SELECT, INSERT, UPDATE, DELETE ON ekapon.program_interest_allowed_barangays TO ekapon_admin;
GRANT USAGE, SELECT ON SEQUENCE ekapon.program_interest_campaigns_id_seq,
    ekapon.program_interest_people_id_seq, ekapon.program_interest_activity_id_seq TO ekapon_admin;
GRANT SELECT ON ekapon.program_interest_campaigns,
    ekapon.program_interest_allowed_barangays, ekapon.program_interest_people,
    ekapon.program_interest_activity TO ekapon_admin;

COMMIT;
