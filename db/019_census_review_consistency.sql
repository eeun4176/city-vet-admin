BEGIN;
ALTER TABLE ekapon.census_owners
 ADD COLUMN IF NOT EXISTS decision_reason text CHECK (length(decision_reason) <= 1000),
 ADD COLUMN IF NOT EXISTS match_fingerprint text,
 ADD COLUMN IF NOT EXISTS applied_owner_id uuid;
-- Keep previous decisions even when a pending sheet is corrected and its rows replaced.
CREATE TABLE IF NOT EXISTS ekapon.census_decision_activity (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 submission_id uuid NOT NULL REFERENCES ekapon.census_submissions(id) ON DELETE CASCADE,
 census_owner_id uuid NOT NULL,
 actor_id bigint REFERENCES ekapon.accounts(id) ON DELETE SET NULL,
 actor_name text NOT NULL,
 before_data jsonb NOT NULL, after_data jsonb NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS census_decision_activity_submission_idx ON ekapon.census_decision_activity(submission_id,id DESC);
GRANT SELECT,INSERT ON ekapon.census_decision_activity TO ekapon_admin;
GRANT USAGE,SELECT ON SEQUENCE ekapon.census_decision_activity_id_seq TO ekapon_admin;
DO $$ DECLARE definition text; marker text; BEGIN
 SELECT pg_get_functiondef('ekapon.decide_census_submission(uuid,text,text)'::regprocedure) INTO definition;
 IF position('CENSUS_CONFIRMED_MATCH_REQUIRED' in definition)=0 THEN
  marker := '        FOR v_owner IN SELECT * FROM ekapon.census_owners';
  IF position(marker in definition)=0 THEN RAISE EXCEPTION 'Census review function changed; review migration 019.'; END IF;
  definition:=replace(definition,marker,$guard$
        -- CENSUS_CONFIRMED_MATCH_REQUIRED: old pending matches need a fresh staff review.
        IF EXISTS (SELECT 1 FROM ekapon.census_owners WHERE submission_id=p_id
          AND decision IN ('merge','replace','keep')
          AND (matched_owner_id IS NULL OR length(btrim(coalesce(decision_reason,'')))<3 OR match_fingerprint IS NULL)) THEN
          RAISE EXCEPTION 'Compare each selected owner and provide a reason before approval.' USING ERRCODE='22023';
        END IF;
$guard$ || marker);
  marker := '            FOR v_pet IN SELECT * FROM ekapon.census_pets';
  IF position(marker in definition)=0 THEN RAISE EXCEPTION 'Census pet loop changed; review migration 019.'; END IF;
  definition:=replace(definition,marker,'            UPDATE ekapon.census_owners SET applied_owner_id=v_reg_owner WHERE id=v_owner.id;' || E'\n' || marker);
  EXECUTE definition;
 END IF;
END $$;
COMMIT;
