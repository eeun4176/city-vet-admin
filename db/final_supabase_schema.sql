CREATE FUNCTION ekapon.audit_row()
RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = pg_catalog, ekapon
AS $$
DECLARE
    v_old jsonb;
    v_new jsonb;
    v_id text;
    v_actor bigint;
BEGIN
    v_actor := NULLIF(current_setting('app.account_id', true), '')::bigint;
    IF TG_OP <> 'INSERT' THEN
        v_old := to_jsonb(OLD) - ARRAY['password_hash'];
        v_id := to_jsonb(OLD)->>'id';
    END IF;
    IF TG_OP <> 'DELETE' THEN
        v_new := to_jsonb(NEW) - ARRAY['password_hash'];
        v_id := to_jsonb(NEW)->>'id';
    END IF;

    INSERT INTO ekapon.audit_log (table_name, record_id, operation, account_id, old_data, new_data)
    VALUES (TG_TABLE_NAME, v_id, TG_OP, v_actor, v_old, v_new);
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END
$$;

CREATE FUNCTION ekapon.set_account_key()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, ekapon
AS $$
DECLARE
    v_zip text;
    v_prefix text;
    v_mobile text;
    v_key_number bigint;
BEGIN
    IF TG_OP = 'UPDATE' AND OLD.account_key IS DISTINCT FROM NEW.account_key THEN
        RAISE EXCEPTION 'Account keys cannot be changed.' USING ERRCODE = '22023';
    END IF;
    IF TG_OP = 'INSERT' AND NEW.account_type IN ('Paravet', 'User') THEN
        IF NEW.barangay_id IS NULL THEN
            RAISE EXCEPTION 'A barangay is required for portal accounts.' USING ERRCODE = '23502';
        END IF;
        SELECT zip INTO STRICT v_zip FROM ekapon.barangays WHERE id = NEW.barangay_id;
        v_prefix := CASE NEW.account_type WHEN 'Paravet' THEN 'PV' ELSE 'US' END;
        v_key_number := nextval('ekapon.account_key_seq');
        NEW.account_key := v_prefix
            || to_char(clock_timestamp() AT TIME ZONE 'Asia/Manila', 'YYYY')
            || '-TMP' || lpad(v_key_number::text, greatest(3, length(v_key_number::text)), '0')
            || '-' || v_zip;
    END IF;
    IF NEW.mobile IS NOT NULL THEN
        v_mobile := regexp_replace(NEW.mobile, '[- ]', '', 'g');
        NEW.mobile := substr(v_mobile, 1, 4) || '-' || substr(v_mobile, 5, 3) || '-' || substr(v_mobile, 8, 4);
    END IF;
    NEW.updated_at := now();
    RETURN NEW;
END
$$;

