CREATE FUNCTION ekapon.issue_temp_password(p_account_id bigint)
RETURNS text
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = pg_catalog, ekapon, extensions
AS $$
DECLARE
    v_account ekapon.accounts%ROWTYPE;
    v_password text := '';
    v_alphabet constant text := 'ABCDEFGHJKLMNPQRTUVWXYabcdefghjkmnpqrtuvwxy346789';
    v_byte integer;
    v_limit integer := (256 / length(v_alphabet)) * length(v_alphabet);
BEGIN
    SELECT * INTO STRICT v_account FROM ekapon.accounts WHERE id = p_account_id FOR UPDATE;
    IF v_account.account_type NOT IN ('Paravet', 'User')
       OR v_account.status = 'Disabled'
       OR v_account.archived_at IS NOT NULL THEN
        RAISE EXCEPTION 'Temporary passwords are only for active portal accounts.' USING ERRCODE = '22023';
    END IF;

    UPDATE ekapon.temp_credentials
       SET destroyed_at = COALESCE(destroyed_at, now())
     WHERE account_id = p_account_id AND used_at IS NULL AND destroyed_at IS NULL;

    WHILE length(v_password) < 8 LOOP
        v_byte := get_byte(extensions.gen_random_bytes(1), 0);
        IF v_byte < v_limit THEN
            v_password := v_password || substr(v_alphabet, (v_byte % length(v_alphabet)) + 1, 1);
        END IF;
    END LOOP;
    v_password := substr(v_password, 1, 4) || '-' || substr(v_password, 5, 4);

    INSERT INTO ekapon.temp_credentials (account_id, password_hash, expires_at)
    VALUES (p_account_id, extensions.crypt(v_password, extensions.gen_salt('bf', 12)), now() + interval '15 minutes');

    UPDATE ekapon.accounts
       SET status = 'Temporary password pending', password_hash = NULL,
           failed_login_count = 0, locked_until = NULL
     WHERE id = p_account_id;
    RETURN v_password;
END
$$;

CREATE FUNCTION ekapon.verify_temp_password(p_account_key text, p_password text, p_ip inet DEFAULT NULL)
RETURNS TABLE (o_ok boolean, o_reason text, o_account_id bigint, o_attempts_left integer)
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = pg_catalog, ekapon, extensions
AS $$
DECLARE
    v_account ekapon.accounts%ROWTYPE;
    v_credential ekapon.temp_credentials%ROWTYPE;
    v_left integer;
BEGIN
    SELECT * INTO v_account
      FROM ekapon.accounts
     WHERE account_key = upper(btrim(p_account_key)) AND archived_at IS NULL
     FOR UPDATE;
    IF NOT FOUND THEN
        PERFORM ekapon.log_login_attempt(p_account_key, NULL, 'temporary', false, 'unknown account', p_ip);
        RETURN QUERY SELECT false, 'invalid'::text, NULL::bigint, NULL::integer;
        RETURN;
    END IF;
    IF v_account.status = 'Locked' OR v_account.locked_until > now() THEN
        PERFORM ekapon.log_login_attempt(p_account_key, v_account.id, 'temporary', false, 'locked', p_ip);
        RETURN QUERY SELECT false, 'locked'::text, v_account.id, 0;
        RETURN;
    END IF;
    IF v_account.status = 'Temporary password expired' THEN
        PERFORM ekapon.log_login_attempt(p_account_key, v_account.id, 'temporary', false, 'expired', p_ip);
        RETURN QUERY SELECT false, 'expired'::text, v_account.id, NULL::integer;
        RETURN;
    END IF;

    SELECT * INTO v_credential
      FROM ekapon.temp_credentials
     WHERE account_id = v_account.id AND used_at IS NULL AND destroyed_at IS NULL
     ORDER BY created_at DESC, id DESC
     LIMIT 1 FOR UPDATE;
    IF NOT FOUND OR v_account.status NOT IN ('Temporary password pending', 'Temporary password expired') THEN
        PERFORM ekapon.log_login_attempt(p_account_key, v_account.id, 'temporary', false, 'invalid', p_ip);
        RETURN QUERY SELECT false, 'invalid'::text, v_account.id, NULL::integer;
        RETURN;
    END IF;
    IF v_credential.locked_at IS NOT NULL THEN
        PERFORM ekapon.log_login_attempt(p_account_key, v_account.id, 'temporary', false, 'locked', p_ip);
        RETURN QUERY SELECT false, 'locked'::text, v_account.id, 0;
        RETURN;
    END IF;
    IF v_credential.expires_at <= now() THEN
        UPDATE ekapon.temp_credentials SET destroyed_at = now() WHERE id = v_credential.id;
        UPDATE ekapon.accounts SET status = 'Temporary password expired' WHERE id = v_account.id;
        PERFORM ekapon.log_login_attempt(p_account_key, v_account.id, 'temporary', false, 'expired', p_ip);
        RETURN QUERY SELECT false, 'expired'::text, v_account.id, NULL::integer;
        RETURN;
    END IF;

    IF extensions.crypt(COALESCE(p_password, ''), v_credential.password_hash) = v_credential.password_hash THEN
        UPDATE ekapon.temp_credentials SET used_at = now() WHERE id = v_credential.id;
        UPDATE ekapon.accounts SET status = 'Password reset required' WHERE id = v_account.id;
        PERFORM ekapon.log_login_attempt(p_account_key, v_account.id, 'temporary', true, NULL, p_ip);
        RETURN QUERY SELECT true, 'ok'::text, v_account.id, NULL::integer;
        RETURN;
    END IF;

    v_left := greatest(3 - v_credential.failed_attempts - 1, 0);
    UPDATE ekapon.temp_credentials
       SET failed_attempts = failed_attempts + 1,
           locked_at = CASE WHEN failed_attempts + 1 >= 3 THEN now() ELSE locked_at END
     WHERE id = v_credential.id;
    IF v_left = 0 THEN
        UPDATE ekapon.accounts SET status = 'Locked' WHERE id = v_account.id;
    END IF;
    PERFORM ekapon.log_login_attempt(p_account_key, v_account.id, 'temporary', false,
                                     CASE WHEN v_left = 0 THEN 'locked' ELSE 'invalid' END, p_ip);
    RETURN QUERY SELECT false, CASE WHEN v_left = 0 THEN 'locked' ELSE 'invalid' END::text, v_account.id, v_left;
END
$$;

CREATE FUNCTION ekapon.set_permanent_password(p_account_id bigint, p_password text)
RETURNS void
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = pg_catalog, ekapon, extensions
AS $$
DECLARE
    v_status ekapon.account_status;
BEGIN
    IF p_password IS NULL OR length(p_password) < 8 OR length(p_password) > 200
       OR p_password !~ '[A-Za-z]' OR p_password !~ '[0-9]' THEN
        RAISE EXCEPTION 'Password must be at least 8 characters and contain a letter and a number.'
            USING ERRCODE = '22023';
    END IF;
    SELECT status INTO STRICT v_status FROM ekapon.accounts WHERE id = p_account_id FOR UPDATE;
    IF v_status NOT IN ('Active', 'Password reset required') THEN
        RAISE EXCEPTION 'This account cannot set a permanent password in its current state.'
            USING ERRCODE = '22023';
    END IF;
    UPDATE ekapon.accounts
       SET password_hash = extensions.crypt(p_password, extensions.gen_salt('bf', 12)),
           status = 'Active', failed_login_count = 0, locked_until = NULL
     WHERE id = p_account_id;
    UPDATE ekapon.temp_credentials
       SET destroyed_at = COALESCE(destroyed_at, now())
     WHERE account_id = p_account_id AND used_at IS NULL AND destroyed_at IS NULL;
END
$$;

CREATE FUNCTION ekapon.verify_password(p_login text, p_password text, p_ip inet DEFAULT NULL)
RETURNS TABLE (o_ok boolean, o_reason text, o_account_id bigint)
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = pg_catalog, ekapon, extensions
AS $$
DECLARE
    v_account ekapon.accounts%ROWTYPE;
    v_max_attempts integer := ekapon.setting_int('max_login_attempts');
    v_reason text;
BEGIN
    SELECT * INTO v_account
      FROM ekapon.accounts
     WHERE (lower(username) = lower(p_login) OR account_key = upper(btrim(p_login)))
       AND archived_at IS NULL
     FOR UPDATE;
    IF NOT FOUND THEN
        PERFORM ekapon.log_login_attempt(p_login, NULL, 'permanent', false, 'unknown account', p_ip);
        RETURN QUERY SELECT false, 'invalid'::text, NULL::bigint;
        RETURN;
    END IF;
    v_reason := CASE
        WHEN v_account.status = 'Disabled' THEN 'disabled'
        WHEN v_account.status = 'Locked' OR v_account.locked_until > now() THEN 'locked'
        WHEN v_account.status IN ('Temporary password pending', 'Temporary password expired') THEN 'use_temporary_password'
        WHEN v_account.status = 'Password reset required' THEN 'must_reset'
    END;
    IF v_reason IS NOT NULL THEN
        PERFORM ekapon.log_login_attempt(p_login, v_account.id, 'permanent', false, v_reason, p_ip);
        RETURN QUERY SELECT false, v_reason, v_account.id;
        RETURN;
    END IF;

    IF v_account.password_hash IS NOT NULL
       AND extensions.crypt(COALESCE(p_password, ''), v_account.password_hash) = v_account.password_hash THEN
        UPDATE ekapon.accounts
           SET failed_login_count = 0, locked_until = NULL, last_login_at = now()
         WHERE id = v_account.id;
        PERFORM ekapon.log_login_attempt(p_login, v_account.id, 'permanent', true, NULL, p_ip);
        RETURN QUERY SELECT true, 'ok'::text, v_account.id;
        RETURN;
    END IF;

    UPDATE ekapon.accounts
       SET locked_until = CASE WHEN failed_login_count + 1 >= v_max_attempts
                               THEN now() + interval '15 minutes' ELSE locked_until END,
           failed_login_count = CASE WHEN failed_login_count + 1 >= v_max_attempts
                                     THEN 0 ELSE failed_login_count + 1 END
     WHERE id = v_account.id;
    PERFORM ekapon.log_login_attempt(p_login, v_account.id, 'permanent', false, 'invalid', p_ip);
    RETURN QUERY SELECT false, 'invalid'::text, v_account.id;
END
$$;

CREATE FUNCTION ekapon.archive_records(p_table text, p_ids bigint[], p_restore boolean DEFAULT false)
RETURNS integer
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = pg_catalog, ekapon
AS $$
DECLARE
    v_count integer;
BEGIN
    IF p_table <> 'accounts' THEN
        RAISE EXCEPTION 'Unsupported archive target.' USING ERRCODE = '22023';
    END IF;
    UPDATE ekapon.accounts
       SET archived_at = CASE WHEN p_restore THEN NULL ELSE now() END
     WHERE id = ANY(COALESCE(p_ids, ARRAY[]::bigint[]))
       AND archived_at IS DISTINCT FROM CASE WHEN p_restore THEN NULL ELSE now() END;
    GET DIAGNOSTICS v_count = ROW_COUNT;
    RETURN v_count;
END
$$;

